-- 连接到 bookmall_book 后执行：
--   psql -U postgres -h localhost -p 5432 -d bookmall_book -f docs/sql/03-bookmall-book.sql

CREATE TABLE category (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(32) NOT NULL,
    CONSTRAINT uq_category_name UNIQUE (name),
    CONSTRAINT ck_category_name_len CHECK (char_length(name) BETWEEN 1 AND 32)
);

CREATE TABLE book (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint         NOT NULL,
    title       varchar(128)   NOT NULL,
    author      varchar(64)    NOT NULL,
    cover_url   varchar(255),
    price       numeric(10, 2) NOT NULL,
    stock       integer        NOT NULL,
    description text,
    isbn        varchar(32),
    on_sale     boolean        NOT NULL,
    CONSTRAINT fk_book_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_book_price_nonneg CHECK (price >= 0),
    CONSTRAINT ck_book_stock_nonneg CHECK (stock >= 0)
);

CREATE INDEX idx_book_category_id ON book (category_id);
CREATE INDEX idx_book_title ON book (title);

COMMENT ON TABLE category IS '图书分类。第一版由种子数据提供。';
COMMENT ON COLUMN category.id IS '分类 ID';
COMMENT ON COLUMN category.name IS '分类名称，全库唯一';

COMMENT ON TABLE book IS '图书。isbn 可空，第六期起详情返回该列。';
COMMENT ON COLUMN book.id IS '图书 ID';
COMMENT ON COLUMN book.category_id IS '所属分类 ID，外键引用 category.id';
COMMENT ON COLUMN book.title IS '书名';
COMMENT ON COLUMN book.author IS '作者';
COMMENT ON COLUMN book.cover_url IS '封面图片地址，可空';
COMMENT ON COLUMN book.price IS '单价，单位元，最多两位小数';
COMMENT ON COLUMN book.stock IS '可售库存，必须大于等于 0。扣减时须满足 stock >= 扣减数量';
COMMENT ON COLUMN book.description IS '简介，可空';
COMMENT ON COLUMN book.isbn IS 'ISBN，可空，最长 32';
COMMENT ON COLUMN book.on_sale IS '是否在售。true=在售，false=下架';

CREATE TABLE stock_change (
    token      varchar(64) PRIMARY KEY,
    book_id    bigint   NOT NULL,
    quantity   integer  NOT NULL,
    deducted   boolean  NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_stock_change_quantity_pos CHECK (quantity > 0)
);

COMMENT ON TABLE stock_change IS '库存扣减与回补的幂等记录。同一 token 只扣一次、只回补一次。';
COMMENT ON COLUMN stock_change.token IS '一次扣减的令牌，由订单服务生成';
COMMENT ON COLUMN stock_change.book_id IS '图书 ID';
COMMENT ON COLUMN stock_change.quantity IS '本次变更数量';
COMMENT ON COLUMN stock_change.deducted IS 'true=已扣减，false=已回补';
COMMENT ON COLUMN stock_change.created_at IS '首次记录时间，UTC';

CREATE TABLE undo_log (
    id            SERIAL       NOT NULL,
    branch_id     BIGINT       NOT NULL,
    xid           VARCHAR(128) NOT NULL,
    context       VARCHAR(128) NOT NULL,
    rollback_info BYTEA        NOT NULL,
    log_status    INT          NOT NULL,
    log_created   TIMESTAMP(0) NOT NULL,
    log_modified  TIMESTAMP(0) NOT NULL,
    CONSTRAINT pk_undo_log PRIMARY KEY (id),
    CONSTRAINT ux_undo_log UNIQUE (xid, branch_id)
);
CREATE INDEX ix_log_created ON undo_log (log_created);
COMMENT ON TABLE undo_log IS 'Seata AT 回滚日志。由图书服务在全局事务中写入。';

ALTER TABLE category OWNER TO bookmall_book_app;
ALTER TABLE book OWNER TO bookmall_book_app;
ALTER TABLE stock_change OWNER TO bookmall_book_app;
ALTER TABLE undo_log OWNER TO bookmall_book_app;
ALTER SEQUENCE undo_log_id_seq OWNER TO bookmall_book_app;
