-- 连接到 bookmall_user 后，以超级用户或 bookmall_user_app 执行：
--   psql -U postgres -h localhost -p 5432 -d bookmall_user -f docs/sql/02-bookmall-user.sql

CREATE TABLE user_account (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   varchar(32)  NOT NULL,
    password   varchar(100) NOT NULL,
    nickname   varchar(32)  NOT NULL,
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_account_username UNIQUE (username),
    CONSTRAINT ck_user_account_username_len CHECK (char_length(username) BETWEEN 3 AND 20),
    CONSTRAINT ck_user_account_nickname_len CHECK (char_length(nickname) BETWEEN 1 AND 32)
);

COMMENT ON TABLE user_account IS '用户账号。password 只存 BCrypt 哈希，不存明文。';
COMMENT ON COLUMN user_account.id IS '用户 ID';
COMMENT ON COLUMN user_account.username IS '登录用户名，3–20 个字符，全库唯一，区分大小写';
COMMENT ON COLUMN user_account.password IS '密码的 BCrypt 哈希，禁止存明文。哈希约 60 字符';
COMMENT ON COLUMN user_account.nickname IS '昵称。注册未填时，应用层写入与用户名相同的值';
COMMENT ON COLUMN user_account.created_at IS '账号创建时间，UTC';

ALTER TABLE user_account OWNER TO bookmall_user_app;
