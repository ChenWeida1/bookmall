-- 连接到 bookmall_order 后执行：
--   psql -U postgres -h localhost -p 5432 -d bookmall_order -f docs/sql/04-bookmall-order.sql
-- user_id、book_id 是别的库里的主键，这里不能建外键。

CREATE TABLE cart_item (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  bigint  NOT NULL,
    book_id  bigint  NOT NULL,
    quantity integer NOT NULL,
    CONSTRAINT uq_cart_item_user_book UNIQUE (user_id, book_id),
    CONSTRAINT ck_cart_item_quantity_pos CHECK (quantity > 0)
);

CREATE TABLE order_main (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no     varchar(32)    NOT NULL,
    user_id      bigint         NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    status       smallint       NOT NULL,
    created_at   timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT uq_order_main_order_no UNIQUE (order_no),
    CONSTRAINT ck_order_main_total_nonneg CHECK (total_amount >= 0),
    CONSTRAINT ck_order_main_status CHECK (status IN (1))
);

CREATE TABLE order_item (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint         NOT NULL,
    book_id    bigint         NOT NULL,
    book_title varchar(128)   NOT NULL,
    unit_price numeric(10, 2) NOT NULL,
    quantity   integer        NOT NULL,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES order_main (id),
    CONSTRAINT ck_order_item_unit_price_nonneg CHECK (unit_price >= 0),
    CONSTRAINT ck_order_item_quantity_pos CHECK (quantity > 0)
);

CREATE TABLE stock_hold (
    token      varchar(64) PRIMARY KEY,
    user_id    bigint  NOT NULL,
    book_id    bigint  NOT NULL,
    quantity   integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_stock_hold_quantity_pos CHECK (quantity > 0)
);

CREATE INDEX idx_order_main_user_created ON order_main (user_id, created_at DESC);
CREATE INDEX idx_order_item_order_id ON order_item (order_id);
CREATE INDEX idx_stock_hold_user_id ON stock_hold (user_id);

COMMENT ON TABLE cart_item IS '购物车。同一用户同一图书一行。user_id、book_id 无跨库外键。';
COMMENT ON COLUMN cart_item.id IS '购物车条目 ID';
COMMENT ON COLUMN cart_item.user_id IS '用户 ID。逻辑引用 bookmall_user.user_account.id，不建外键';
COMMENT ON COLUMN cart_item.book_id IS '图书 ID。逻辑引用 bookmall_book.book.id，不建外键';
COMMENT ON COLUMN cart_item.quantity IS '数量，必须为正整数';

COMMENT ON TABLE order_main IS '订单头。';
COMMENT ON COLUMN order_main.id IS '订单主键';
COMMENT ON COLUMN order_main.order_no IS '业务订单号，全局唯一';
COMMENT ON COLUMN order_main.user_id IS '下单用户 ID。逻辑引用用户库，不建外键';
COMMENT ON COLUMN order_main.total_amount IS '订单总金额，单位元';
COMMENT ON COLUMN order_main.status IS '订单状态：1=已创建。预留 2=已取消，第一版检查约束不允许写入';
COMMENT ON COLUMN order_main.created_at IS '下单时间，UTC';

COMMENT ON TABLE order_item IS '订单明细。书名和单价是下单快照。';
COMMENT ON COLUMN order_item.id IS '明细 ID';
COMMENT ON COLUMN order_item.order_id IS '所属订单 ID，外键引用 order_main.id';
COMMENT ON COLUMN order_item.book_id IS '图书 ID。逻辑引用图书库，不建外键';
COMMENT ON COLUMN order_item.book_title IS '下单时的书名快照，不随图书改名而变化';
COMMENT ON COLUMN order_item.unit_price IS '下单时的单价快照，单位元';
COMMENT ON COLUMN order_item.quantity IS '购买数量，必须为正整数';

COMMENT ON TABLE stock_hold IS '已发起扣减、尚未和订单一起提交的库存占用。进程中断后由下次下单按 token 回补。';
COMMENT ON COLUMN stock_hold.token IS '对应图书库 stock_change.token';
COMMENT ON COLUMN stock_hold.user_id IS '下单用户 ID';
COMMENT ON COLUMN stock_hold.book_id IS '图书 ID';
COMMENT ON COLUMN stock_hold.quantity IS '占用数量';
COMMENT ON COLUMN stock_hold.created_at IS '占用时间，UTC';

ALTER TABLE cart_item OWNER TO bookmall_order_app;
ALTER TABLE order_main OWNER TO bookmall_order_app;
ALTER TABLE order_item OWNER TO bookmall_order_app;
ALTER TABLE stock_hold OWNER TO bookmall_order_app;
